test('generation 5 separates all eight RNG streams and validates new seed fields', () => {
  const spec = worldSpec(42);
  assert.equal(spec.generationVersion, 5);
  assert.equal(Object.keys(spec.seeds).length, 8);
  assert.equal(new Set(Object.values(spec.seeds)).size, 8);
  for (const value of Object.values(spec.seeds)) assert(Number.isInteger(value) && value >= 0 && value <= 65535);
  for (const key of ['villages', 'loot'] as const) {
    for (const value of [undefined, null, -1, 65536, 1.5, NaN]) {
      const broken = structuredClone(spec); (broken.seeds as any)[key] = value;
      assert.throws(() => validateWorld(broken));
    }
    for (const value of [0, 65535]) { const valid = structuredClone(spec); valid.seeds[key] = value; assert.equal(validateWorld(valid).seeds[key], value); }
  }
});

test('village, wildlife, loot and resource seeds can change independently', () => {
  const base = worldSpec(42), a = new WorldManager(base);
  for (const key of ['villages', 'wildlife', 'loot', 'resources'] as const) {
    const changed = structuredClone(base); changed.seeds[key] ^= 65535;
    const b = new WorldManager(changed);
    for (const [x, z] of [[0, 0], [40, 8], [-72, -32], [257, -513]]) {
      assert.equal(a.height(x, z), b.height(x, z)); assert.deepEqual(a.river(x, z), b.river(x, z));
    }
    assert.deepEqual(a.chunk(1, 1).trees, b.chunk(1, 1).trees);
    if (key !== 'resources') assert.deepEqual(a.chunk(1, 1).nodes, b.chunk(1, 1).nodes);
    if (key !== 'villages') assert.deepEqual(a.villages(), b.villages());
  }
  assert.deepEqual(importJSON(exportFull(newState(base))).world, base);
});

test('legacy generations preserve pre-change terrain, chunks, villages and drop outcomes', () => {
  // Captured from commit 80e72ca before changing generation code, not regenerated by this test.
  const fixtures = JSON.parse(readFileSync(new URL('./fixtures/legacy-worlds.json', import.meta.url), 'utf8'));
  for (const { spec, digest } of fixtures) {
    const restored = validateWorld(spec), w = new WorldManager(restored);
    assert.equal(restored.seeds.villages, spec.seeds.wildlife); assert.equal(restored.seeds.loot, spec.seeds.wildlife);
    const samples = {
      surface: [[0, 0], [-71, -45], [256, 32], [-32, 32], [40, 8], [132, 112]].map(([x, z]) => [w.height(x, z), w.river(x, z), w.biome(x, z)]),
      chunks: [w.chunk(0, 0), w.chunk(-1, -1), w.chunk(1, 1)], villages: w.villages()
    };
    assert.equal(createHash('sha256').update(JSON.stringify(samples)).digest('hex'), digest);
    for (let i = 0; i < 100; i++) assert.equal(equipmentDrops(restored.seeds.loot, `actor:${i}`), equipmentDrops(spec.seeds.wildlife, `actor:${i}`));
    const doc = JSON.parse(exportFull(newState(restored))); doc.world = spec;
    assert.deepEqual(importJSON(JSON.stringify(doc)).world, restored);
  }
});

test('camera-relative movement preserves analog strength and limits diagonals', () => {
  const north = cameraRelativeMovement(0, -1, 0); assert.equal(north.x, 0); assert.equal(north.z, -1);
  const west = cameraRelativeMovement(0, -1, Math.PI / 2); assert(Math.abs(west.x + 1) < 1e-10); assert(Math.abs(west.z) < 1e-10);
  const diagonal = cameraRelativeMovement(1, 1, .45); assert(Math.abs(Math.hypot(diagonal.x, diagonal.z) - 1) < 1e-10);
  const analog = cameraRelativeMovement(.2, 0, 2); assert(Math.abs(Math.hypot(analog.x, analog.z) - .2) < 1e-10);
});

test('joystick has a radial dead zone, smooth analog ramp and unit clamp', () => {
  assert.deepEqual(joystickMovement(0, 0), { x: 0, z: 0 });
  assert.deepEqual(joystickMovement(2, 2), { x: 0, z: 0 });
  assert(joystickMovement(12, 0).x > 0 && joystickMovement(12, 0).x < 1);
  assert.equal(joystickMovement(MOVEMENT.joystickRadius, 0).x, 1);
  const far = joystickMovement(1000, -1000); assert(Math.abs(Math.hypot(far.x, far.z) - 1) < 1e-10);
});

test('movement is stable at 30/60/120 FPS and clearing input removes residual velocity', () => {
  const simulate = (fps: number, sprint = false) => {
    const game = new Game(newState(worldSpec(42))); game.paused = false;
    // Isolate movement from encounters; exercise the real terrain and solid collision path.
    game.combat.update = () => {};
    for (let i = 0; i < fps / 2; i++) game.update(1 / fps, { x: 0, z: 1, sprint });
    return game;
  };
  const low = simulate(30), high = simulate(120);
  assert(Math.abs(low.state.player.z - high.state.player.z) < .1);
  assert(simulate(60, true).state.player.z > simulate(60).state.player.z);
  high.stopMovement(); const before = { ...high.state.player };
  high.update(1 / 60); assert.equal(high.state.player.x, before.x); assert.equal(high.state.player.z, before.z);
  const pausedBefore={...high.state.player};high.paused = true; high.update(1, { x: 1, z: 1 }); assert.deepEqual(high.state.player, pausedBefore);
});

test('chunks regenerate after cache eviction at distant positive and negative coordinates', () => {
  const w = new WorldManager(worldSpec(65535));
  const original = structuredClone(w.chunk(-31250, 31249));
  for (let i = 0; i < 140; i++) w.chunk(i + 100, -i - 100);
  assert.deepEqual(w.chunk(-31250, 31249), original);
  assert.equal(new Set(original.nodes.map(n => n.id)).size, original.nodes.length);
});
